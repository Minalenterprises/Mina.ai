import { NextRequest, NextResponse } from "next/server";
import type { DesignSpec } from "@/lib/types";

export const runtime = "nodejs";

interface Body {
  spec: DesignSpec;
}

export async function POST(req: NextRequest) {
  try {
    const body = (await req.json()) as Body;
    if (!body?.spec) {
      return NextResponse.json({ error: "spec required" }, { status: 400 });
    }
    const spec = body.spec;
    const html = buildHtml(spec);

    return new NextResponse(html, {
      headers: {
        "Content-Type": "text/html; charset=utf-8",
        "Content-Disposition": `attachment; filename="minal-${(spec.title || spec.kind).replace(/\s+/g, "-").toLowerCase()}.html"`,
      },
    });
  } catch (err) {
    return NextResponse.json(
      { error: err instanceof Error ? err.message : "internal" },
      { status: 500 }
    );
  }
}

function escapeHtml(s: string): string {
  return String(s || "").replace(/[<>&"]/g, (c) =>
    ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;" }[c]!)
  );
}

